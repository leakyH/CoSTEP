"""Daily and reporting-interval peak metrics."""
import json

import numpy as np


PEAK_VERSION = 'report_rate_peak_macro_mae_v2'
PEAK_KEYS = ('peak_mae', 'peak_mre')


def _peak_numpy(value):
    if hasattr(value, 'detach'):
        value = value.detach().cpu().numpy()
    return np.asarray(value)


def _peak_windows(value, name):
    array = _peak_numpy(value).astype(np.float64, copy=False)
    if array.ndim == 4 and array.shape[-1] == 1:
        array = array[..., 0]
    if array.ndim != 3 or not all(array.shape):
        raise ValueError(f'{name} requires nonempty [window,horizon,node], got {array.shape}')
    if not np.isfinite(array).all():
        raise ValueError(f'{name} contains non-finite data')
    return array


def _peak_origins(value, count):
    if value is None:
        raise ValueError('target origin indices are required')
    array = _peak_numpy(value)
    if array.shape != (count,) or not np.issubdtype(array.dtype, np.integer):
        raise ValueError(f'origin_indices must be an integer vector of length {count}')
    array = array.astype(np.int64)
    if np.any(array < 0) or np.unique(array).size != count:
        raise ValueError('origin_indices must be nonnegative and unique')
    return array


def stitch_peak_trajectories(prediction, groundtruth, origin_indices):
    """Return sorted dates, equal-weight prediction means, and deduplicated truth."""
    pred = _peak_windows(prediction, 'prediction')
    truth = _peak_windows(groundtruth, 'groundtruth')
    if pred.shape != truth.shape:
        raise ValueError('prediction/groundtruth shapes differ')
    if np.any(truth < 0):
        raise ValueError('peak metrics do not accept negative groundtruth')
    origins = _peak_origins(origin_indices, pred.shape[0])
    horizon, nodes = pred.shape[1:]
    order = np.argsort(origins)
    if np.any(np.diff(origins[order]) > horizon):
        raise ValueError('test calendar has uncovered dates')
    length = int(origins.max() - origins.min()) + horizon
    if int(origins.max()) > np.iinfo(np.int64).max - horizon:
        raise ValueError('target date index overflow')
    dates = np.arange(length, dtype=np.int64) + origins.min()
    means = np.zeros((length, nodes), dtype=np.float64)
    observed = np.full_like(means, np.nan)
    counts = np.zeros(length, dtype=np.int64)
    for index in order:
        offset = int(origins[index] - origins.min())
        target = slice(offset, offset + horizon)
        seen = counts[target] > 0
        if not np.allclose(observed[target][seen], truth[index][seen], rtol=0, atol=1e-6):
            raise ValueError(f'conflicting overlapping groundtruth at origin {origins[index]}')
        observed[target][~seen] = truth[index][~seen]
        counts[target] += 1
        # Running mean avoids a potentially overflowing sum of large predictions.
        means[target] += (pred[index] - means[target]) / counts[target, None]
    if np.any(counts == 0) or not np.isfinite(means).all():
        raise ValueError('invalid prediction calendar coverage or numeric overflow')
    return dates, means, observed


def _peak_json(value):
    return json.dumps(value, sort_keys=True, ensure_ascii=False, allow_nan=False)


def peak_error_metrics(prediction, groundtruth, *, origin_indices,
                       dataset_context, node_ids=None,
                       reporting_metadata=None):
    """Select each node's highest report/day, then average absolute event errors.

    Irregular labels require report masks and lengths. Only predictions
    fully covering the selected event are scored; selection never uses coverage.
    peak_mre is the node-macro mean of peak_mae / observed peak daily rate;
    zero-peak nodes remain in MAE but are excluded from MRE (a fraction, not %).
    Daily datasets ignore interval payloads generated by positive-count heuristics.
    Other datasets must set dataset_context.reporting_mode.
    """
    pred = _peak_windows(prediction, 'prediction')
    truth_windows = _peak_windows(groundtruth, 'groundtruth')
    origins = _peak_origins(origin_indices, len(pred))
    dates, _, truth = stitch_peak_trajectories(pred, truth_windows, origins)
    if not isinstance(dataset_context, dict) or not dataset_context.get('dataset'):
        raise ValueError('dataset_context must identify dataset')
    mode = dataset_context.get('reporting_mode')
    if mode is None:
        mode = 'interval' if dataset_context['dataset'] in ('US_STATE', 'JAPAN-Irregular') else 'daily'
    if mode not in ('daily', 'interval'):
        raise ValueError('reporting_mode must be daily or interval')
    nodes = truth.shape[1]
    node_ids = list(range(nodes)) if node_ids is None else [
        v.item() if isinstance(v, np.generic) else v for v in node_ids]
    if len(node_ids) != nodes or len(set(map(_peak_json, node_ids))) != nodes:
        raise ValueError('node_ids must uniquely identify every node')
    mask = np.ones_like(truth, dtype=bool)
    lengths = np.ones_like(truth, dtype=np.int64)
    valid_windows = np.ones_like(pred, dtype=bool)
    if mode == 'interval':
        if reporting_metadata is None:
            raise ValueError('interval peak scoring requires reporting_metadata')
        calendars = {}
        for key in ('future_report_mask', 'future_report_interval', 'future_event_valid'):
            if key not in reporting_metadata:
                raise ValueError(f'reporting_metadata missing {key}')
            value = _peak_windows(reporting_metadata[key], key)
            if value.shape != pred.shape:
                raise ValueError(f'{key} shape differs from prediction')
            if key != 'future_report_interval' and not np.isin(value, [0, 1]).all():
                raise ValueError(f'{key} must be Boolean')
            if key == 'future_event_valid':
                valid_windows = value.astype(bool)
            else:
                calendars[key] = stitch_peak_trajectories(value, value, origins)[2]
        mask = calendars['future_report_mask'].astype(bool)
        raw_lengths = calendars['future_report_interval']
        if np.any(raw_lengths < 0) or np.any(raw_lengths != np.floor(raw_lengths)):
            raise ValueError('report intervals must be nonnegative integers')
        if np.any(mask & (raw_lengths < 1)) or np.any((truth > 0) & ~mask):
            raise ValueError('report mask/length inconsistent with labels')
        lengths = raw_lengths.astype(np.int64)
        if reporting_metadata.get('origin_index') is not None:
            if not np.array_equal(_peak_numpy(reporting_metadata['origin_index']).reshape(-1), origins):
                raise ValueError('reporting metadata origins differ')
    rates = np.divide(truth, lengths, out=np.zeros_like(truth), where=lengths > 0)
    # Missing events are never confused with genuine zero-count reports.
    indices = np.argmax(np.where(mask, rates, -np.inf), axis=0)
    indices = np.where(mask.any(axis=0), indices, -1)
    rows = []
    support = []
    for node, index in enumerate(indices):
        row = dict(node_index=node, node_id=node_ids[node], peak_report_date=None,
                   peak_interval_start=None, peak_interval_length=None,
                   peak_report_total=None, peak_daily_rate=None,
                   eligible_origin_count=0, peak_mae=None, peak_mre=None, status='no_report')
        selected = np.array([], dtype=np.int64)
        if index >= 0:
            end = int(dates[index]); length = int(lengths[index, node]); start = end-length+1
            selected = np.flatnonzero((origins <= start) & (origins+pred.shape[1]-1 >= end))
            # Dataset boundary events may have provisional lengths but no valid
            # observed interval. Preserve the selected peak and mark unavailable.
            validity = [valid_windows[i, end-origins[i], node] for i in selected]
            if validity and any(validity) and not all(validity):
                raise ValueError('conflicting event validity among complete forecast windows')
            selected = np.array([i for i in selected if valid_windows[i, end-origins[i], node]], dtype=np.int64)
            errors = [abs(pred[i, start-origins[i]:end-origins[i]+1, node].sum()-truth[index,node])/length
                      for i in selected]
            error = float(np.mean(errors)) if errors else None
            if error is not None and not np.isfinite(error):
                raise ValueError('numeric overflow in peak error')
            row.update(peak_report_date=end, peak_interval_start=start,
                       peak_interval_length=length, peak_report_total=float(truth[index,node]),
                       peak_daily_rate=float(rates[index,node]), eligible_origin_count=len(selected),
                       peak_mae=error, status='ok' if errors else 'no_complete_valid_forecast')
        if row['peak_mae'] is not None and row['peak_daily_rate'] > 0:
            row['peak_mre'] = row['peak_mae'] / row['peak_daily_rate']
            if not np.isfinite(row['peak_mre']):
                raise ValueError('numeric overflow in relative peak error')
        support.append(origins[selected].tolist())
        rows.append(row)
    values = [r['peak_mae'] for r in rows if r['peak_mae'] is not None]
    relative = [r['peak_mre'] for r in rows if r['peak_mre'] is not None]
    return dict(peak_status='ok' if values else 'unavailable', version=PEAK_VERSION,
                peak_mae=float(np.mean(values)) if values else None,
                peak_mre=float(np.mean(relative)) if relative else None,
                valid_node_counts={'peak_mae':len(values), 'peak_mre':len(relative)}, node_count=nodes,
                eligible_origin_count=sum(r['eligible_origin_count'] for r in rows),
                unavailable_node_count=nodes-len(values),
                calendar_start=int(dates[0]), calendar_end=int(dates[-1]),
                calendar_length=len(dates), dataset_context=dataset_context,
                reporting_mode=mode, scoring_support=support, nodes=rows)

